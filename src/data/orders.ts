export function createTrackedOrderFromCheckout(
  orderId: string,
  cart: CartItem[],
  orderDetails: CustomerOrderDetails,
  total: number
): TrackedOrder {
  const steps = [
    {
      status: 'Confirmed' as OrderStatus,
      label: 'Order Confirmed',
      description: 'Your request is recorded. Mandeep Singh is confirming batch dispatch.',
      timestamp: 'Just now',
      completed: true,
      current: true,
    },
    {
      status: 'Processing' as OrderStatus,
      label: 'Confection & Gift Packaging',
      description: 'Small-batch tempering, ganache filling & satin ribbon tie.',
      completed: false,
      current: false,
    },
    {
      status: 'Out for Delivery' as OrderStatus,
      label: 'Out for Delivery in Aligarh',
      description: 'Courier dispatch in temperature-regulated packaging.',
      completed: false,
      current: false,
    },
    {
      status: 'Delivered' as OrderStatus,
      label: 'Delivered',
      description: 'Delivered to your doorstep in Aligarh.',
      completed: false,
      current: false,
    },
  ];

  return {
    orderId,
    customerName: orderDetails.fullName,
    phone: orderDetails.phone,
    date: 'Just now',
    deliveryArea: `${orderDetails.area}, ${orderDetails.city}`,
    deliveryTimeSlot: orderDetails.deliveryTimeSlot,
    status: 'Confirmed',
    items: cart.map((c) => ({
      name: c.product.name,
      variant: c.selectedVariant.name,
      quantity: c.quantity,
      price: c.selectedVariant.price,
    })),
    totalAmount: total,
    paymentMethod: orderDetails.paymentMethod === 'cod' ? 'Cash on Delivery' : 'WhatsApp Confirmation',
    estimatedDelivery: `${orderDetails.deliveryDate || 'Today'} (${orderDetails.deliveryTimeSlot})`,
    steps,
  };
}
